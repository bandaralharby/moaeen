/* توحيد أسماء مواد الصف الرابع وربط القرآن والدراسات الإسلامية كما تظهر في نموذج المعلمة */
(function(){
const d=window.lessonData&&window.lessonData['الرابع الابتدائي'];
if(!d)return;
const q=d['القرآن الكريم']||[];
const isl=d['الدراسات الإسلامية']||[];
if(q.length||isl.length)d['القرآن الكريم والدراسات الإسلامية']=[...q,...isl];
if(d['لغتي الجميلة'])d['لغتي']=d['لغتي الجميلة'];
delete d['القرآن الكريم'];
delete d['لغتي الجميلة'];
})();